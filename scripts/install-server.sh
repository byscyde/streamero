#!/usr/bin/env bash
# STREAMERO server installer for Debian/Ubuntu (and other Linux distributions with Docker).
#
#   git clone https://github.com/mmzlopasa/streamero.git && cd streamero
#   sudo ./scripts/install-server.sh
#
# Non-interactive:
#   sudo STREAMERO_DOMAIN=music.example.com ADMIN_EMAIL=me@example.com ./scripts/install-server.sh --yes       # built-in HTTPS (Caddy)
#   sudo STREAMERO_DOMAIN=music.example.com STREAMERO_PROXY=host-nginx ./scripts/install-server.sh --yes       # your existing nginx
#   sudo STREAMERO_MODE=lan ./scripts/install-server.sh --yes                                                   # home network only
#
# What it does: installs Docker if missing, generates strong secrets into .env (never overwrites an
# existing .env), starts the stack (with automatic HTTPS when a domain is given), waits until the API is
# ready and prints the address to enter in the iPhone app plus the admin credentials.
set -euo pipefail

cd "$(dirname "$0")/.."
ROOT="$(pwd)"
YES=0
[ "${1:-}" = "--yes" ] && YES=1

bold() { printf '\033[1m%s\033[0m\n' "$*"; }
info() { printf '  \033[36m•\033[0m %s\n' "$*"; }
warn() { printf '  \033[33m!\033[0m %s\n' "$*"; }
die() { printf '\033[31mGreška/Error:\033[0m %s\n' "$*" >&2; exit 1; }
ask() { # ask "Question" default -> echo answer
  local q="$1" def="${2:-}" a
  if [ $YES -eq 1 ]; then echo "$def"; return; fi
  read -r -p "$q${def:+ [$def]}: " a </dev/tty || true
  echo "${a:-$def}"
}
secret() { openssl rand -base64 48 | tr -d '\n=/+' | cut -c1-48; }

[ "$(id -u)" -eq 0 ] || die "Pokreni sa sudo / run with sudo: sudo $0"
command -v openssl >/dev/null || { apt-get update -qq && apt-get install -y -qq openssl; }

bold "STREAMERO — instalacija servera"

# 1) Docker ---------------------------------------------------------------------------------------
if ! command -v docker >/dev/null || ! docker compose version >/dev/null 2>&1; then
  info "Docker nije instaliran. Instaliram Docker Engine + Compose (get.docker.com)…"
  [ $YES -eq 1 ] || [ "$(ask 'Nastaviti? (da/ne)' 'da')" = "da" ] || die "Docker je potreban."
  curl -fsSL https://get.docker.com | sh
  systemctl enable --now docker
fi
docker compose version >/dev/null || die "docker compose plugin nije dostupan"
info "$(docker --version)"

# 2) Configuration --------------------------------------------------------------------------------
if [ -f .env ]; then
  warn ".env već postoji — zadržavam postojeće postavke (ništa se ne prepisuje)."
  # shellcheck disable=SC1091
  set -a; . ./.env; set +a
else
  # A new .env means new database/storage passwords. Data volumes from an earlier install keep the old
  # ones (PostgreSQL stores its password only on first start), so the API would fail with
  # "password authentication failed". Stop here instead of starting a stack that cannot work.
  if docker volume inspect streamero_pgdata >/dev/null 2>&1; then
    die "Pronađeni su podaci starije instalacije (Docker volumen streamero_pgdata), ali .env ne postoji.
   Lozinke u novom .env ne bi odgovarale postojećoj bazi.
   - Ako imaš stari .env: vrati ga u $ROOT/.env i ponovno pokreni skriptu.
   - Za potpuno brisanje i instalaciju od nule: sudo ./scripts/uninstall-server.sh --purge, pa ponovno ova skripta."
  fi
  DOMAIN="${STREAMERO_DOMAIN:-}"
  MODE="${STREAMERO_MODE:-}"
  PROXY="${STREAMERO_PROXY:-}"
  HOST_NGINX=0
  if command -v nginx >/dev/null && { systemctl is-active --quiet nginx 2>/dev/null || pgrep -x nginx >/dev/null; }; then HOST_NGINX=1; fi
  if [ -z "$DOMAIN" ] && [ "$MODE" != "lan" ]; then
    echo
    echo "  Kako ćeš pristupati serveru s iPhonea?"
    echo "   1) Preko interneta s domenom, koristeći MOJ POSTOJEĆI nginx (reverse proxy + certbot HTTPS)"
    echo "   2) Preko interneta s domenom, STREAMERO sam radi HTTPS (Caddy; portovi 80/443 moraju biti slobodni)"
    echo "   3) Samo u kućnoj mreži (http://IP-adresa:8088)"
    if [ $HOST_NGINX -eq 1 ]; then def=1; info "Otkriven je nginx koji već radi na ovom serveru → preporučujem opciju 1"; else def=2; fi
    choice="$(ask 'Odaberi 1, 2 ili 3' "$def")"
    case "$choice" in
      1) PROXY=host-nginx ;;
      2) PROXY=caddy ;;
      *) MODE=lan ;;
    esac
    if [ "$MODE" != "lan" ]; then
      DOMAIN="$(ask 'Domena (DNS A zapis mora pokazivati na ovaj server; iPhone aplikacija koristi app.streamero.net)' 'app.streamero.net')"
      [ -n "$DOMAIN" ] || die "Domena je obavezna za ovu opciju"
    fi
  fi
  if [ -n "$DOMAIN" ] && [ -z "$PROXY" ]; then PROXY=$([ $HOST_NGINX -eq 1 ] && echo host-nginx || echo caddy); fi
  [ "$MODE" = "lan" ] && PROXY=none
  LAN_IP="$(hostname -I 2>/dev/null | awk '{print $1}')"
  if [ -n "$DOMAIN" ]; then
    PUBLIC_BASE_URL="https://$DOMAIN"
  else
    PUBLIC_BASE_URL="http://${LAN_IP:-localhost}:8088"
  fi
  ADMIN_EMAIL="${ADMIN_EMAIL:-$(ask 'Email administratora' 'admin@streamero.local')}"
  ADMIN_PASSWORD="${ADMIN_PASSWORD:-$(openssl rand -base64 18 | tr -d '\n=/+')}"
  umask 077
  cat > .env <<EOF
# Generated by scripts/install-server.sh on $(date -u +%FT%TZ). Keep this file secret (chmod 600).
PUBLIC_BASE_URL=$PUBLIC_BASE_URL
STREAMERO_DOMAIN=$DOMAIN
# caddy = built-in HTTPS, host-nginx = your existing nginx proxies to 127.0.0.1:HTTP_PORT, none = LAN
STREAMERO_PROXY=$PROXY
HTTP_PORT=8088
POSTGRES_PASSWORD=$(secret)
S3_ACCESS_KEY=streamero
S3_SECRET_KEY=$(secret)
JWT_ACCESS_SECRET=$(secret)
MEDIA_SIGNING_SECRET=$(secret)
BOOTSTRAP_ADMIN_EMAIL=$ADMIN_EMAIL
BOOTSTRAP_ADMIN_PASSWORD=$ADMIN_PASSWORD
# Optional: email (verification & password reset), e.g. smtps://user:pass@smtp.example.com:465
SMTP_URL=
MAIL_FROM="STREAMERO <no-reply@scyde.dev>"
APP_LINK_BASE=https://app.streamero.net/
# Optional: folder on this server to import music from (mounted read-only into the worker as /import)
IMPORT_ALLOWED_DIRS=
IMPORT_ALLOWED_HOSTS=
# Optional: Google sign-in (OAuth client IDs from console.cloud.google.com)
GOOGLE_IOS_CLIENT_ID=
GOOGLE_WEB_CLIENT_ID=
YOUTUBE_API_KEY=
WORKER_CONCURRENCY=1
WORKER_CPUS=2
WORKER_MEMORY=2g
EOF
  chmod 600 .env
  info "Generiran .env s jakim lozinkama ($ROOT/.env)"
  set -a; . ./.env; set +a
fi

COMPOSE=(docker compose -f docker-compose.yml)
if [ -f docker-compose.import.yml ]; then COMPOSE+=(-f docker-compose.import.yml); fi
case "${STREAMERO_PROXY:-}" in
  host-nginx) COMPOSE+=(-f docker-compose.localhost.yml) ;;
  caddy) COMPOSE+=(-f docker-compose.https.yml) ;;
  *) if [ -n "${STREAMERO_DOMAIN:-}" ]; then COMPOSE+=(-f docker-compose.https.yml); fi ;;
esac

# 3) Firewall (only if ufw is active) -----------------------------------------------------------------
if command -v ufw >/dev/null && ufw status | grep -q "Status: active"; then
  if [ "${STREAMERO_PROXY:-}" = "caddy" ]; then ufw allow 80/tcp >/dev/null; ufw allow 443/tcp >/dev/null; ufw allow 443/udp >/dev/null
  elif [ "${STREAMERO_PROXY:-}" = "host-nginx" ]; then ufw allow 'Nginx Full' >/dev/null 2>&1 || { ufw allow 80/tcp >/dev/null; ufw allow 443/tcp >/dev/null; }
  else ufw allow 8088/tcp >/dev/null; fi
  info "UFW: otvoreni potrebni portovi"
fi

# 4) Start ------------------------------------------------------------------------------------------------
bold "Gradim i pokrećem servise (prvi put traje nekoliko minuta)…"
if [ "${STREAMERO_SKIP_BUILD:-0}" = 1 ]; then "${COMPOSE[@]}" up -d; else "${COMPOSE[@]}" up -d --build; fi

info "Čekam da API bude spreman…"
for _ in $(seq 1 90); do
  if curl -fsS "http://127.0.0.1:${HTTP_PORT:-8088}/readyz" >/dev/null 2>&1; then READY=1; break; fi
  sleep 2
done
[ "${READY:-0}" = 1 ] || { "${COMPOSE[@]}" logs --tail 80 api; die "API se nije pokrenuo — pogledaj logove iznad."; }

# 5) Existing host nginx: virtual host + certificate -----------------------------------------------------
if [ "${STREAMERO_PROXY:-}" = "host-nginx" ]; then
  if [ -d /etc/nginx/sites-available ]; then VHOST=/etc/nginx/sites-available/streamero.conf; else VHOST=/etc/nginx/conf.d/streamero.conf; fi
  if [ -f "$VHOST" ]; then
    warn "$VHOST već postoji — ne diram ga."
  else
    sed -e "s/music.example.com/$STREAMERO_DOMAIN/g" -e "s/127.0.0.1:8088/127.0.0.1:${HTTP_PORT:-8088}/" infra/host-nginx-streamero.conf > "$VHOST"
    # Hosts without IPv6 cannot bind [::]:80.
    if [ ! -s /proc/net/if_inet6 ]; then sed -i '/listen \[::\]/d' "$VHOST"; fi
    if [ -d /etc/nginx/sites-enabled ]; then ln -sf "$VHOST" /etc/nginx/sites-enabled/streamero.conf; fi
    info "nginx vhost: $VHOST"
  fi
  nginx -t || die "nginx konfiguracija nije ispravna (nginx -t). Popravi pa pokreni skriptu ponovno."
  systemctl reload nginx 2>/dev/null || nginx -s reload
  info "nginx ponovno učitan"
  if ! grep -q "listen.*443" "$VHOST" 2>/dev/null; then
    if ! command -v certbot >/dev/null; then
      if [ $YES -eq 1 ] || [ "$(ask 'Instalirati certbot za besplatni HTTPS certifikat? (da/ne)' 'da')" = "da" ]; then
        apt-get update -qq && apt-get install -y -qq certbot python3-certbot-nginx
      fi
    fi
    if command -v certbot >/dev/null; then
      CERT_EMAIL="${CERTBOT_EMAIL:-${BOOTSTRAP_ADMIN_EMAIL:-}}"
      certbot --nginx -d "$STREAMERO_DOMAIN" --redirect --agree-tos -n ${CERT_EMAIL:+-m "$CERT_EMAIL"} \
        || warn "certbot nije uspio — provjeri DNS za $STREAMERO_DOMAIN pa pokreni: sudo certbot --nginx -d $STREAMERO_DOMAIN"
    else
      warn "Bez certbota nema HTTPS-a; iPhone se neće moći spojiti izvan kućne mreže."
    fi
  fi
fi

if [ -n "${STREAMERO_DOMAIN:-}" ]; then
  info "Provjeravam HTTPS za $STREAMERO_DOMAIN…"
  for _ in $(seq 1 30); do curl -fsS "https://$STREAMERO_DOMAIN/healthz" >/dev/null 2>&1 && HTTPS_OK=1 && break; sleep 3; done
  [ "${HTTPS_OK:-0}" = 1 ] && info "HTTPS radi: https://$STREAMERO_DOMAIN" \
    || warn "HTTPS još ne radi. Provjeri DNS zapis za $STREAMERO_DOMAIN, portove 80/443 i logove (nginx: /var/log/nginx/error.log, caddy: docker compose logs caddy)."
fi

CREDS="$ROOT/streamero-admin-credentials.txt"
if [ ! -f "$CREDS" ] && [ -n "${BOOTSTRAP_ADMIN_PASSWORD:-}" ]; then
  umask 077
  printf 'Admin: %s\nEmail: %s\nLozinka/Password: %s\n' "$PUBLIC_BASE_URL/admin/" "$BOOTSTRAP_ADMIN_EMAIL" "$BOOTSTRAP_ADMIN_PASSWORD" > "$CREDS"
fi

echo
bold "✅ STREAMERO radi!"
echo "   Adresa za iPhone aplikaciju:  $PUBLIC_BASE_URL"
echo "   Admin panel (preglednik):     $PUBLIC_BASE_URL/admin/"
echo "   Admin email:                  ${BOOTSTRAP_ADMIN_EMAIL:-?}"
[ -n "${BOOTSTRAP_ADMIN_PASSWORD:-}" ] && echo "   Admin lozinka:                $BOOTSTRAP_ADMIN_PASSWORD   (spremljeno i u $CREDS)"
echo
echo "   Sljedeći koraci: prijavi se u admin panel, učitaj glazbu (Upload & import),"
echo "   zatim u aplikaciji upiši gornju adresu i prijavi se istim emailom i lozinkom."
