import { readFileSync } from 'node:fs';
import { afterAll, afterEach, beforeAll, describe, expect, it, vi } from 'vitest';
import { MetadataService } from '../../src/metadata/metadata.service.js';
import { USER_AGENT } from '../../src/metadata/musicbrainz.js';
import { auth, makeFixture, registerUser, startApp, uploadFile, type TestContext } from '../helpers.js';

let ctx: TestContext;
let editor: Awaited<ReturnType<typeof registerUser>>;
let listener: Awaited<ReturnType<typeof registerUser>>;
let coverJpeg: Buffer;

const REC = '11111111-1111-4111-8111-111111111111';
const REL = '22222222-2222-4222-8222-222222222222';

const recording = {
  id: REC,
  score: 100,
  title: 'Harbour Lights',
  length: 6000,
  'artist-credit': [{ name: 'Sea Glass', joinphrase: ' & ', artist: { id: 'a1', name: 'Sea Glass' } }, { name: 'Tide', artist: { id: 'a2', name: 'Tide' } }],
  'first-release-date': '2019-06-14',
  releases: [
    { id: '33333333-3333-4333-8333-333333333333', title: 'Bootleg Live', status: 'Bootleg', date: '2018', 'release-group': { id: 'g0', 'primary-type': 'Album' } },
    { id: REL, title: 'Coastlines', status: 'Official', date: '2019-06-14', 'release-group': { id: 'g1', 'primary-type': 'Album', 'secondary-types': [] } },
  ],
  genres: [{ name: 'Dream Pop', count: 5 }, { name: 'Shoegaze', count: 2 }],
  tags: [{ name: 'chill', count: 1 }],
  isrcs: ['GBAAA1900001'],
};
const release = {
  id: REL,
  title: 'Coastlines',
  date: '2019-06-14',
  'artist-credit': [{ name: 'Sea Glass' }],
  'release-group': { id: 'g1', 'primary-type': 'Album', 'secondary-types': [], genres: [{ name: 'indie', count: 1 }] },
  'label-info': [{ label: { name: 'Lighthouse Records' } }],
  media: [
    { position: 1, tracks: [{ position: 1, number: '1', recording: { id: 'other' } }] },
    { position: 2, tracks: [{ position: 3, number: '3', recording: { id: REC } }] },
  ],
};

const json = (body: unknown, status = 200) => new Response(JSON.stringify(body), { status, headers: { 'Content-Type': 'application/json' } });

/** Fake MusicBrainz + Cover Art Archive. Records every request so tests can assert politeness headers. */
function mockNetwork(opts: { down?: boolean; noCover?: boolean } = {}) {
  const calls: { url: string; ua: string | null }[] = [];
  const spy = vi.spyOn(globalThis, 'fetch').mockImplementation(async (input: any, init?: any) => {
    const url = String(input instanceof URL ? input.href : input);
    calls.push({ url, ua: new Headers(init?.headers).get('user-agent') });
    if (opts.down) throw new TypeError('fetch failed');
    const u = new URL(url);
    if (u.hostname === 'coverartarchive.org') {
      if (opts.noCover) return new Response('not found', { status: 404 });
      return new Response(coverJpeg, { status: 200, headers: { 'Content-Type': 'image/jpeg' } });
    }
    if (u.hostname !== 'musicbrainz.org') throw new Error(`unexpected host ${u.hostname}`);
    if (u.pathname === '/ws/2/recording') return json({ recordings: [recording] });
    if (u.pathname === `/ws/2/recording/${REC}`) return json(recording);
    if (u.pathname === `/ws/2/release/${REL}`) return json(release);
    return json({ error: 'Not Found' }, 404);
  });
  return { calls, spy };
}

async function ingest(name: string, tags: string[]) {
  const file = makeFixture(name, ['-f', 'lavfi', '-i', 'sine=frequency=330:duration=6', '-c:a', 'flac', ...tags]);
  const up = await uploadFile(ctx, editor.token, readFileSync(file), name, 'media', { authorizationNote: 'Test fixture generated by FFmpeg' });
  const res = await ctx.runner.run(up.job.id);
  expect(res.ok).toBe(true);
  const job = await ctx.http.get(`/v1/admin/jobs/${up.job.id}`).set(auth(editor.token)).expect(200);
  return job.body.result.trackId as string;
}

beforeAll(async () => {
  ctx = await startApp();
  editor = await registerUser(ctx, 'editor');
  listener = await registerUser(ctx);
  coverJpeg = readFileSync(makeFixture('caa-front.jpg', ['-f', 'lavfi', '-i', 'color=c=0x0ea5e9:s=500x500', '-frames:v', '1']));
});
afterEach(() => vi.restoreAllMocks());
afterAll(() => ctx.close());

describe('metadata lookup (MusicBrainz + Cover Art Archive)', () => {
  it('searches recordings for editors with a proper User-Agent', async () => {
    const { calls } = mockNetwork();
    await ctx.http.get('/v1/admin/metadata/search').query({ q: 'sea glass harbour' }).set(auth(listener.token)).expect(403);
    const res = await ctx.http.get('/v1/admin/metadata/search').query({ q: 'Sea Glass - Harbour Lights' }).set(auth(editor.token)).expect(200);
    expect(res.body.items).toEqual([
      {
        id: REC,
        title: 'Harbour Lights',
        artist: 'Sea Glass & Tide',
        album: 'Coastlines',
        albumId: REL,
        year: 2019,
        durationMs: 6000,
        genres: ['dream pop', 'shoegaze'],
        coverUrl: `https://coverartarchive.org/release/${REL}/front-250`,
        score: 100,
      },
    ]);
    expect(calls).toHaveLength(1);
    expect(calls[0].ua).toBe(USER_AGENT);
    const q = new URL(calls[0].url).searchParams;
    expect(q.get('query')).toBe('artist:"Sea Glass" AND recording:"Harbour Lights"');
    expect(q.get('fmt')).toBe('json');
    await ctx.http.get('/v1/admin/metadata/search').query({ q: 'x' }).set(auth(editor.token)).expect(400);
  });

  it('answers 503 when MusicBrainz is unreachable', async () => {
    mockNetwork({ down: true });
    const res = await ctx.http.get('/v1/admin/metadata/search').query({ q: 'anything at all' }).set(auth(editor.token)).expect(503);
    expect(res.body.error.code).toBe('metadata_unavailable');
  });

  it('applies title, artist, album, year, genres, track number and cover art', async () => {
    const trackId = await ingest('harbour.flac', ['-metadata', 'title=harbour lights (demo)']);
    const before = await ctx.http.get(`/v1/admin/tracks/${trackId}`).set(auth(editor.token)).expect(200);
    expect(before.body.artist.name).toBe('Unknown Artist');
    const oldAlbumId = before.body.album.id;

    const { calls } = mockNetwork();
    await ctx.http.post('/v1/admin/metadata/apply').set(auth(listener.token)).send({ trackId, recordingId: REC }).expect(403);
    const res = await ctx.http.post('/v1/admin/metadata/apply').set(auth(editor.token)).send({ trackId, recordingId: REC, overwrite: true }).expect(200);
    expect(res.body).toMatchObject({
      id: trackId,
      title: 'Harbour Lights',
      artist: { name: 'Sea Glass & Tide' },
      album: { title: 'Coastlines' },
      trackNumber: 3,
      discNumber: 2,
      genres: ['dream pop', 'shoegaze', 'indie'],
      isrc: 'GBAAA1900001',
      applied: { cover: 'stored' },
    });
    expect(res.body.applied.fields).toEqual(expect.arrayContaining(['title', 'artist', 'album', 'trackNumber', 'genres', 'year', 'artwork']));
    expect(res.body.artworkUrl).toMatch(/\/v1\/artwork\//);
    // Best official release was chosen, not the bootleg; every MusicBrainz call carried the User-Agent.
    expect(calls.map((c) => new URL(c.url).pathname)).toEqual([`/ws/2/recording/${REC}`, `/ws/2/release/${REL}`, `/release/${REL}/front-500`]);
    expect(calls.every((c) => c.ua === USER_AGENT)).toBe(true);

    const album = await ctx.db.one('SELECT al.release_date::text AS d, al.label, ar.name FROM albums al JOIN artists ar ON ar.id = al.artist_id WHERE al.id = $1', [res.body.album.id]);
    expect(album).toEqual({ d: '2019-06-14', label: 'Lighthouse Records', name: 'Sea Glass' });
    const art = await ctx.http.get(new URL(res.body.artworkUrl).pathname).expect(200);
    expect(art.headers['content-type']).toBe('image/jpeg');
    // The auto-created single the file came with is gone now that it is empty.
    expect(await ctx.db.one('SELECT id FROM albums WHERE id = $1', [oldAlbumId])).toBeNull();
    const audit = await ctx.db.one(`SELECT metadata FROM audit_logs WHERE action = 'metadata.apply' AND target_id = $1`, [trackId]);
    expect(audit.metadata).toMatchObject({ recordingId: REC, releaseId: REL, cover: 'stored' });
  });

  it('without overwrite only fills missing values and keeps existing artwork', async () => {
    const trackId = await ingest('kept.flac', ['-metadata', 'title=My Own Title', '-metadata', 'artist=Real Band', '-metadata', 'genre=Rock']);
    mockNetwork({ noCover: true });
    const res = await ctx.http.post('/v1/admin/metadata/apply').set(auth(editor.token)).send({ trackId, recordingId: REC, releaseId: REL }).expect(200);
    expect(res.body).toMatchObject({ title: 'My Own Title', artist: { name: 'Real Band' }, genres: ['rock'], album: { title: 'Coastlines' }, trackNumber: 3 });
    expect(res.body.applied.cover).toBe('kept'); // Coastlines already has the cover stored by the previous test
    expect(res.body.applied.fields).not.toContain('title');
    await ctx.http.post('/v1/admin/metadata/apply').set(auth(editor.token)).send({ trackId: '00000000-0000-4000-8000-000000000000', recordingId: REC }).expect(404);
  });

  it('auto-fills only confident matches', async () => {
    const metadata = ctx.app.get(MetadataService);
    const good = await ingest('auto.flac', ['-metadata', 'title=Harbour Lights', '-metadata', 'artist=Sea Glass & Tide']);
    mockNetwork();
    const outcome = await metadata.autofill(good);
    expect(outcome?.fields).toEqual(expect.arrayContaining(['album', 'genres']));
    const t = await ctx.http.get(`/v1/admin/tracks/${good}`).set(auth(editor.token)).expect(200);
    expect(t.body.album.title).toBe('Coastlines');

    const weak = await ingest('weak.flac', ['-metadata', 'title=Completely Different Song', '-metadata', 'artist=Someone Else']);
    expect(await metadata.autofill(weak)).toBeNull();
    const w = await ctx.http.get(`/v1/admin/tracks/${weak}`).set(auth(editor.token)).expect(200);
    expect(w.body.artist.name).toBe('Someone Else');
  });
});
