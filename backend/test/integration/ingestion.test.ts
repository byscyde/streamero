import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { auth, fixturesDir, makeFixture, registerUser, startApp, uploadFile, type TestContext } from '../helpers.js';

let ctx: TestContext;
let admin: Awaited<ReturnType<typeof registerUser>>;
let listener: Awaited<ReturnType<typeof registerUser>>;
let flacTrackId: string;
let videoId: string;

const mediaPath = (url: string) => new URL(url).pathname;

beforeAll(async () => {
  ctx = await startApp();
  admin = await registerUser(ctx, 'admin');
  listener = await registerUser(ctx);
});
afterAll(() => ctx.close());

async function runJob(jobId: string) {
  const res = await ctx.runner.run(jobId);
  const job = await ctx.http.get(`/v1/admin/jobs/${jobId}`).set(auth(admin.token)).expect(200);
  return { res, job: job.body };
}

describe('audio ingestion', () => {
  it('ingests a tagged 24-bit FLAC with embedded artwork into all profiles including ALAC lossless', async () => {
    const cover = makeFixture('cover.png', ['-f', 'lavfi', '-i', 'color=c=0x6d28d9:s=600x600', '-frames:v', '1']);
    const flac = makeFixture('song.flac', [
      '-f', 'lavfi', '-i', 'sine=frequency=440:duration=8:sample_rate=48000', '-i', cover,
      '-map', '0:a', '-map', '1:v', '-c:a', 'flac', '-sample_fmt', 's32', '-c:v', 'png', '-disposition:v', 'attached_pic',
      '-metadata', 'title=Neon Tide', '-metadata', 'artist=Aurora Lane', '-metadata', 'album=Night Signals',
      '-metadata', 'track=2/9', '-metadata', 'date=2023-04-01', '-metadata', 'genre=Synthwave;Electronic',
      '-metadata', 'LYRICS=[00:01.00]First light\n[00:04.00]Second wave',
    ]);
    const up = await uploadFile(ctx, admin.token, readFileSync(flac), 'Neon Tide.flac', 'media', { authorizationNote: 'Test fixture generated by FFmpeg' });
    const { res, job } = await runJob(up.job.id);
    expect(res.ok).toBe(true);
    expect(job.status).toBe('succeeded');
    expect(job.progress).toBe(100);
    flacTrackId = job.result.trackId;
    expect(job.result.renditions.map((r: any) => r.profile)).toEqual(['data_saver', 'standard', 'high', 'lossless']);

    const track = await ctx.http.get(`/v1/tracks/${flacTrackId}`).set(auth(listener.token)).expect(200);
    expect(track.body).toMatchObject({
      title: 'Neon Tide',
      artist: { name: 'Aurora Lane' },
      album: { title: 'Night Signals' },
      trackNumber: 2,
      genres: ['synthwave', 'electronic'],
      hasLyrics: true,
      sourceQuality: { codec: 'flac', lossless: true, sampleRate: 48000, bitDepth: 24 },
    });
    expect(track.body.artworkUrl).toMatch(/\/v1\/artwork\//);

    // Artwork is public and cacheable.
    const art = await ctx.http.get(mediaPath(track.body.artworkUrl)).query({ size: 'small' }).expect(200);
    expect(art.headers['content-type']).toBe('image/jpeg');
    expect(art.headers['cache-control']).toContain('immutable');

    const lyrics = await ctx.http.get(`/v1/tracks/${flacTrackId}/lyrics`).set(auth(listener.token)).expect(200);
    expect(lyrics.body.synced).toBe(true);
    expect(lyrics.body.lines[1]).toMatchObject({ startMs: 4000, text: 'Second wave' });
  });

  it('streams lossless only as real ALAC and supports byte ranges', async () => {
    const s = await ctx.http.get(`/v1/tracks/${flacTrackId}/stream`).query({ profile: 'lossless' }).set(auth(listener.token)).expect(200);
    expect(s.body).toMatchObject({ profile: 'lossless', mimeType: 'audio/mp4', delivery: { codec: 'alac', lossless: true }, source: { codec: 'flac', lossless: true } });
    expect(JSON.stringify(s.body)).not.toMatch(/renditions\/audio|originals\//); // storage keys never leak

    const full = await ctx.http.get(mediaPath(s.body.url)).expect(200);
    expect(full.headers['accept-ranges']).toBe('bytes');
    expect(Number(full.headers['content-length'])).toBe(s.body.sizeBytes);
    const part = await ctx.http.get(mediaPath(s.body.url)).set('Range', 'bytes=0-99').expect(206);
    expect(part.headers['content-range']).toBe(`bytes 0-99/${s.body.sizeBytes}`);
    expect(part.body.length).toBe(100);
    await ctx.http.get(mediaPath(s.body.url)).set('Range', `bytes=${s.body.sizeBytes + 10}-`).expect(416);

    const high = await ctx.http.get(`/v1/tracks/${flacTrackId}/stream`).query({ profile: 'high' }).set(auth(listener.token)).expect(200);
    expect(high.body.delivery).toMatchObject({ codec: 'aac', lossless: false });
    expect(high.body.delivery.bitrateKbps).toBeGreaterThan(150);

    // Tampered tokens are rejected.
    const tampered = mediaPath(s.body.url).replace(/.$/, (c: string) => (c === 'A' ? 'B' : 'A'));
    await ctx.http.get(tampered).expect(401);
  });

  it('detects duplicates by checksum', async () => {
    const up = await uploadFile(ctx, admin.token, readFileSync(path.join(fixturesDir, 'song.flac')), 'copy.flac', 'media');
    const { job } = await runJob(up.job.id);
    expect(job.result).toMatchObject({ duplicate: true, trackId: flacTrackId });
  });

  it('never offers lossless for a lossy MP3 and reuses the compatible original', async () => {
    const mp3 = makeFixture('lofi.mp3', ['-f', 'lavfi', '-i', 'sine=frequency=330:duration=5', '-c:a', 'libmp3lame', '-b:a', '128k', '-metadata', 'title=Lo Fi', '-metadata', 'artist=Aurora Lane']);
    const up = await uploadFile(ctx, admin.token, readFileSync(mp3), 'lofi.mp3', 'media');
    const { job } = await runJob(up.job.id);
    expect(job.status).toBe('succeeded');
    const profiles = job.result.renditions.map((r: any) => `${r.profile}:${r.action}`);
    expect(profiles).toContain('standard:reuse_original');
    expect(profiles.some((p: string) => p.startsWith('lossless'))).toBe(false);
    const s = await ctx.http.get(`/v1/tracks/${job.result.trackId}/stream`).query({ profile: 'lossless' }).set(auth(listener.token)).expect(200);
    expect(s.body.profile).not.toBe('lossless');
    expect(s.body.delivery.lossless).toBe(false);
  });

  it('resumes multi-chunk uploads sent out of order (WAV -> ALAC)', async () => {
    const wav = makeFixture('long.wav', ['-f', 'lavfi', '-i', 'sine=frequency=220:duration=50:sample_rate=48000', '-ac', '2', '-c:a', 'pcm_s16le']);
    const data = readFileSync(wav);
    expect(data.length).toBeGreaterThan(8 * 1024 * 1024);
    const created = await ctx.http.post('/v1/admin/uploads').set(auth(admin.token)).send({ filename: 'long.wav', totalBytes: data.length, purpose: 'media' }).expect(201);
    const { id, chunkBytes, totalChunks } = created.body;
    expect(totalChunks).toBe(2);
    await ctx.http.put(`/v1/admin/uploads/${id}/chunks/1`).set(auth(admin.token)).set('Content-Type', 'application/octet-stream').send(data.subarray(chunkBytes)).expect(200);
    const incomplete = await ctx.http.post(`/v1/admin/uploads/${id}/complete`).set(auth(admin.token)).expect(409);
    expect(incomplete.body.error.details.missingChunks).toEqual([0]);
    const status = await ctx.http.get(`/v1/admin/uploads/${id}`).set(auth(admin.token)).expect(200);
    expect(status.body.missingChunks).toEqual([0]);
    await ctx.http.put(`/v1/admin/uploads/${id}/chunks/0`).set(auth(admin.token)).set('Content-Type', 'application/octet-stream').send(data.subarray(0, 100)).expect(400);
    await ctx.http.put(`/v1/admin/uploads/${id}/chunks/0`).set(auth(admin.token)).set('Content-Type', 'application/octet-stream').send(data.subarray(0, chunkBytes)).expect(200);
    const done = await ctx.http.post(`/v1/admin/uploads/${id}/complete`).set(auth(admin.token)).expect(200);
    const { job } = await runJob(done.body.job.id);
    expect(job.status).toBe('succeeded');
    expect(job.result.renditions.find((r: any) => r.profile === 'lossless')).toMatchObject({ lossless: true });
  });

  it('rejects disallowed file types and fails corrupted media permanently', async () => {
    await ctx.http.post('/v1/admin/uploads').set(auth(admin.token)).send({ filename: 'evil.sh', totalBytes: 10, purpose: 'media' }).expect(415);
    await ctx.http.post('/v1/admin/uploads').set(auth(listener.token)).send({ filename: 'a.mp3', totalBytes: 10, purpose: 'media' }).expect(403);
    const junk = Buffer.alloc(4096, 7);
    const up = await uploadFile(ctx, admin.token, junk, 'broken.mp3', 'media');
    const { res, job } = await runJob(up.job.id);
    expect(res).toMatchObject({ ok: false, permanent: true });
    expect(job.status).toBe('failed');
    expect(job.error).toMatch(/not a supported media file/);
    const retried = await ctx.http.post(`/v1/admin/jobs/${up.job.id}/retry`).set(auth(admin.token)).expect(200);
    expect(retried.body.status).toBe('queued');
  });

  it('refuses YouTube URL imports up front', async () => {
    const res = await ctx.http.post('/v1/admin/imports/url').set(auth(admin.token)).send({ url: 'https://www.youtube.com/watch?v=dQw4w9WgXcQ', authorizationNote: 'I own this' }).expect(400);
    expect(res.body.error.message).toMatch(/YouTube/);
  });
});

describe('video ingestion', () => {
  it('packages HLS with an audio-only rendition, thumbnail, timeline preview and embedded subtitles', async () => {
    const srt = path.join(fixturesDir, 'embedded.srt');
    writeFileSync(srt, '1\n00:00:00,500 --> 00:00:02,000\nEmbedded hello\n');
    const mp4 = makeFixture('clip.mp4', [
      '-f', 'lavfi', '-i', 'testsrc=size=1280x720:rate=30:duration=6', '-f', 'lavfi', '-i', 'sine=frequency=500:duration=6', '-i', srt,
      '-map', '0:v', '-map', '1:a', '-map', '2:s', '-c:v', 'libx264', '-preset', 'ultrafast', '-c:a', 'aac', '-c:s', 'mov_text',
      '-metadata:s:s:0', 'language=eng', '-metadata:s:a:0', 'language=eng', '-metadata', 'title=Night Drive (Official Video)', '-metadata', 'artist=Aurora Lane',
    ]);
    const up = await uploadFile(ctx, admin.token, readFileSync(mp4), 'clip.mp4', 'media');
    const { job } = await runJob(up.job.id);
    expect(job.status).toBe('succeeded');
    videoId = job.result.videoId;

    const v = await ctx.http.get(`/v1/videos/${videoId}`).set(auth(listener.token)).expect(200);
    expect(v.body.video).toMatchObject({ title: 'Night Drive (Official Video)', hasAudioOnly: true, hasTimelinePreview: true, qualities: [720, 540, 360] });
    expect(v.body.video.subtitles[0]).toMatchObject({ language: 'en' });
  });

  it('attaches an uploaded SRT and exposes it in the HLS master playlist', async () => {
    await ctx.http.patch(`/v1/admin/videos/${videoId}`).set(auth(admin.token)).send({ downloadable: true }).expect(200);
    const srt = Buffer.from('1\r\n00:00:01,000 --> 00:00:03,000\r\nBok svijete\r\n', 'utf8');
    const up = await uploadFile(ctx, admin.token, srt, 'hr.srt', 'subtitle', { videoId, language: 'hr', label: 'Hrvatski', isDefault: true });
    const { job } = await runJob(up.job.id);
    expect(job.status).toBe('succeeded');

    const s = await ctx.http.get(`/v1/videos/${videoId}/stream`).set(auth(listener.token)).expect(200);
    expect(s.body.qualities.map((q: any) => q.height)).toEqual([720, 540, 360]);
    expect(s.body.audioOnly.mimeType).toBe('audio/mp4');
    expect(s.body.subtitles.map((x: any) => x.language).sort()).toEqual(['en', 'hr']);

    const master = await ctx.http.get(mediaPath(s.body.hlsUrl)).expect(200);
    const text = master.text;
    expect(text).toContain('#EXT-X-MEDIA:TYPE=SUBTITLES,GROUP-ID="subs",NAME="Hrvatski",LANGUAGE="hr",DEFAULT=YES');
    expect(text).toMatch(/#EXT-X-STREAM-INF:[^\n]*SUBTITLES="subs"/);
    expect(text).toContain('TYPE=AUDIO');

    const subUri = text.match(/URI="(subs\/[^"]+\.m3u8)"/)![1];
    const base = mediaPath(s.body.hlsUrl).replace(/master\.m3u8$/, '');
    const subPlaylist = await ctx.http.get(base + subUri).expect(200);
    expect(subPlaylist.text).toContain('#EXT-X-ENDLIST');
    const vttName = subPlaylist.text.split('\n').find((l: string) => l.endsWith('.vtt'))!;
    const vtt = await ctx.http.get(base + 'subs/' + vttName).expect(200);
    expect(vtt.text).toMatch(/^WEBVTT\nX-TIMESTAMP-MAP=MPEGTS:\d+,LOCAL:00:00:00.000/);

    // Variant playlist + a segment are reachable through the same grant, but nothing outside it.
    const variant = await ctx.http.get(base + s.body.qualities[2].url.split('/').slice(-2).join('/')).expect(200);
    const seg = variant.text.split('\n').find((l: string) => l.endsWith('.ts'))!;
    const segRes = await ctx.http.get(base + '360p/' + seg).buffer(true).expect(200);
    expect(segRes.headers['content-type']).toBe('video/mp2t');
    await ctx.http.get(base + '..%2F..%2Foriginals').expect(404);

    // Sidecar VTT for the client-side renderer.
    const side = await ctx.http.get(mediaPath(s.body.subtitles.find((x: any) => x.language === 'hr').vttUrl)).expect(200);
    expect(side.text).toContain('Bok svijete');
  });

  it('removes catalog entries without deleting shared media', async () => {
    const t = await ctx.db.one('SELECT album_id FROM tracks WHERE id = $1', [flacTrackId]);
    const album = await ctx.db.one('SELECT artwork_asset_id FROM albums WHERE id = $1', [t.album_id]);
    await ctx.http.delete(`/v1/admin/tracks/${flacTrackId}`).set(auth(admin.token)).expect(200);
    await ctx.http.get(`/v1/tracks/${flacTrackId}`).set(auth(listener.token)).expect(404);
    // Album artwork is still referenced by the album and must survive.
    await ctx.http.get(`/v1/artwork/${album.artwork_asset_id}`).expect(200);
    const res = await ctx.http.delete(`/v1/admin/videos/${videoId}`).set(auth(admin.token)).expect(200);
    expect(res.body.deletedAssets).toBeGreaterThanOrEqual(5);
  });
});
